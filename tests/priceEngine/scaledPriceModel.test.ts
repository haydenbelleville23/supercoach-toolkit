import { readFileSync } from "node:fs";
import path from "node:path";

import { beforeAll, describe, expect, it } from "vitest";

import {
  BASE_MAGIC_NUMBER_2026,
  estimateBaseMagicNumber,
} from "@/lib/priceEngine/baseMagicNumber";
import { buildScaledRoundInputs } from "@/lib/priceEngine/buildScaledRoundInputs";
import { calculateScaledRoundPrices } from "@/lib/priceEngine/calculateScaledRoundPrices";
import { evaluateScaledRound } from "@/lib/priceEngine/evaluateScaledRound";
import { normaliseSuperCoachPlayer } from "@/lib/supercoach/normalisePlayer";

import type { Player } from "@/types/player";
import type { SuperCoachPlayer } from "@/types/supercoach";

describe("calculateScaledRoundPrices", () => {
  it("conserves the pool and freezes non-eligible players", () => {
    const result = calculateScaledRoundPrices({
      baseMagicNumber: 5400,
      anchorTotal: 1_200_000,
      players: [
        { playerId: 1, oldPrice: 500_000, category: "eligible", threeRoundAverage: 110 },
        { playerId: 2, oldPrice: 300_000, category: "eligible", threeRoundAverage: 40 },
        { playerId: 3, oldPrice: 200_000, category: "under3", threeRoundAverage: 0 },
        { playerId: 4, oldPrice: 200_000, category: "didNotPlay", threeRoundAverage: 0 },
      ],
    });

    const [p1, p2, p3, p4] = result.players;

    expect(p3.predictedPrice).toBe(200_000);
    expect(p4.predictedPrice).toBe(200_000);
    expect(p1.predictedPrice % 100).toBe(0);

    // Eligible players share the 800k left after the frozen players.
    expect(
      Math.abs(p1.predictedPrice + p2.predictedPrice - 800_000),
    ).toBeLessThanOrEqual(100);

    expect(result.effectiveMagicNumber).toBeCloseTo(5400 * result.k, 8);
  });
});

describe("estimateBaseMagicNumber", () => {
  it("recovers baseMN from prices generated by the scaled model", () => {
    const k = 0.98;
    const baseMN = 5412.15;

    const samples = [
      [500_000, 110],
      [300_000, 40],
      [420_000, 95],
      [250_000, 70],
      [610_000, 100],
    ].map(([oldPrice, threeRoundAverage]) => ({
      oldPrice,
      threeRoundAverage,
      newPrice: k * (0.75 * oldPrice + 0.25 * baseMN * threeRoundAverage),
    }));

    const estimate = estimateBaseMagicNumber(samples);

    expect(estimate?.baseMagicNumber).toBeCloseTo(baseMN, 6);
    expect(estimate?.k).toBeCloseTo(k, 8);
  });

  it("returns null without enough samples", () => {
    expect(estimateBaseMagicNumber([])).toBeNull();
  });
});

describe("scaled model on 2026 published prices", () => {
  let players: Player[] = [];

  beforeAll(() => {
    const raw = JSON.parse(
      readFileSync(
        path.resolve("data/2026/players-complete.json"),
        "utf8",
      ),
    ) as SuperCoachPlayer[];

    players = raw.map((player) => normaliseSuperCoachPlayer(player));
  }, 60_000);

  const roundError = (round: number) =>
    evaluateScaledRound(players, round, BASE_MAGIC_NUMBER_2026);

  it("averages under $50 error across Rounds 2-18", () => {
    let totalError = 0;
    let compared = 0;

    for (let round = 2; round <= 18; round++) {
      const evaluation = roundError(round);

      if (evaluation) {
        totalError += evaluation.totalPriceError;
        compared += evaluation.playersCompared;
      }
    }

    expect(compared).toBeGreaterThan(5000);
    expect(totalError / compared).toBeLessThan(50);
  });

  it.each([
    [2, 29],
    [11, 23],
    [12, 21],
  ])(
    "reproduces the backtest's Round %i error (about $%i)",
    (round, expected) => {
      const evaluation = roundError(round);

      expect(evaluation).not.toBeNull();
      expect(Math.round(evaluation!.averagePriceError)).toBe(expected);
      expect(evaluation!.maxPriceError).toBeLessThanOrEqual(100);
    },
  );

  it("estimates the 2026 baseMN from Round 2 alone", () => {
    const inputs = buildScaledRoundInputs(players, 2);

    const estimate = estimateBaseMagicNumber(
      inputs.players
        .filter((p) => p.category === "eligible" && p.actualPrice !== null)
        .map((p) => ({
          oldPrice: p.oldPrice,
          newPrice: p.actualPrice as number,
          threeRoundAverage: p.threeRoundAverage,
        })),
    );

    expect(estimate).not.toBeNull();
    expect(
      Math.abs(estimate!.baseMagicNumber - BASE_MAGIC_NUMBER_2026),
    ).toBeLessThan(10);
  });
});
